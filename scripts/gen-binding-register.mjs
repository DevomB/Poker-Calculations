import fs from 'node:fs';

const binding = fs.readFileSync('native/binding.cpp', 'utf8');
const re = /exports\.Set\(Napi::String::New\(env,\s*"([^"]+)"\),\s*Napi::Function::New\(env,\s*(\w+)\)\)/g;
const entries = [];
let m;
while ((m = re.exec(binding)) !== null) {
  entries.push({ name: m[1], fn: m[2] });
}

const extra = [
  ['simulateHandOutcomeBatch', 'SimulateHandOutcomeBatch'],
  ['simulateHandOutcomeBatchPacked', 'SimulateHandOutcomeBatchPacked'],
  ['evaluateHandStrengthFastBatch', 'EvaluateHandStrengthFastBatch'],
  ['exactHuEquityVsRandomHandBatch', 'ExactHuEquityVsRandomHandBatch'],
  ['encodePokerState', 'EncodePokerState', 'poker_bind'],
  ['decodePokerState', 'DecodePokerState', 'poker_bind'],
];
for (const row of extra) {
  const [name, fn, ns] = row;
  if (!entries.some((e) => e.name === name)) {
    entries.push({ name, fn, ns: ns ?? null });
  }
}

const cppFns = [...new Set(entries.filter((e) => !e.ns).map((e) => e.fn))];
const lines = entries.map((e) => {
  const sym = e.ns ? `poker_bind::${e.fn}` : e.fn;
  return `        Napi::PropertyDescriptor::Function("${e.name}", ${sym}),`;
});

const out = `// Generated by scripts/gen-binding-register.mjs — do not edit by hand.
#include <napi.h>

#include "binding_batch.hpp"
#include "binding_state.hpp"

${cppFns.map((fn) => `Napi::Value ${fn}(const Napi::CallbackInfo& info);`).join('\n')}

Napi::Object Init(Napi::Env env, Napi::Object exports) {
    exports.DefineProperties({
${lines.join('\n')}
    });
    return exports;
}

NODE_API_MODULE(poker_calculations, Init)
`;

fs.writeFileSync('native/binding_register.cpp', out);
console.log('exports:', entries.length);
